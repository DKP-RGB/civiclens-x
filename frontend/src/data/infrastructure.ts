export const INFRASTRUCTURE_ASSETS: InfrastructureAsset[] = SEEDS.map((seed) => {
  const locality = LOCALITIES.find((l) => l.id === seed.localityId) ?? LOCALITIES[0]
  return {
    id: seed.id,
    name: seed.name,
    type: seed.type,
    localityId: seed.localityId,
    location: {
      lng: Number((locality.centroid.lng + seed.offset[0]).toFixed(6)),
      lat: Number((locality.centroid.lat + seed.offset[1]).toFixed(6)),
    },
    condition: seed.condition,
    lastInspected: daysAgoIso(seed.inspectedDaysAgo),
    criticality: seed.criticality,
    capacityNote: seed.capacityNote,
    notes: seed.notes,
    source: 'simulated',
  }
})
