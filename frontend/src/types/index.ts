// Core domain types shared across the CivicLens X frontend.
// Phase 2 uses bundled mock data behind these types; Phase 9 swaps the source
// for the FastAPI backend without changing page components.

export type Portal = 'citizen' | 'authority'

export type IncidentCategory =
  | 'potholes'
  | 'waterlogging'
  | 'garbage'
  | 'drainage'
  | 'road_damage'
  | 'other'

export type RiskCategory = 'waterlogging' | 'road_deterioration'
export type RiskLevel = 'low' | 'moderate' | 'high' | 'critical'

export type ComplaintStatus =
  | 'submitted'
  | 'under_review'
  | 'inspection_scheduled'
  | 'in_progress'
  | 'resolved'

export type Priority = 'low' | 'medium' | 'high' | 'urgent'

export type DataProvenance =
  | 'verified'
  | 'public_dataset'
  | 'simulated'
  | 'model_output'

export interface LatLng {
  lng: number
  lat: number
}

export interface Locality {
  id: string
  name: string
  centroid: LatLng
  /** Approximate centroid from public place data — not an official ward boundary. */
  coordinatesNote: string
  description: string
  /** Simulated baseline susceptibility used by the illustrative risk score. */
  baseSusceptibility: number
  populationEstimate: number
}

/** Compact per-cell feature record generated by scripts/build_frontend_data.mjs */
export interface GridCellFeature {
  id: string
  lng: number
  lat: number
  localityId: string
  elevation: number
  slope: number
  /** Distance to nearest mapped waterway in metres (drainage proxy). */
  waterDistance: number
  /** Metres of mapped major road within the cell, normalised 0–1. */
  roadDensity: number
  /** Simulated built-up / impervious proxy 0–1 (land-cover data pending). */
  impervious: number
  /** Simulated incidents within 750 m over the trailing 18 months. */
  histWaterlogging: number
  histRoadDamage: number
  dataCompleteness: number
}

export interface RiskFactor {
  key: string
  label: string
  detail: string
  /** Share of the positive contribution, 0–1. */
  contribution: number
  direction: 'increases' | 'reduces'
}

export interface CellRisk {
  cell: GridCellFeature
  probability: number
  level: RiskLevel
  category: RiskCategory
  factors: RiskFactor[]
  /** Illustrative uncertainty band (not model confidence). */
  uncertainty: number
  dataCompleteness: number
}

export interface RiskSummary {
  meanProbability: number
  counts: Record<RiskLevel, number>
  criticalCells: number
  highCells: number
  totalCells: number
}

export interface ComplaintTimelineEntry {
  status: ComplaintStatus
  label: string
  at: string
  note?: string
  actor: 'citizen' | 'authority' | 'system'
}

export interface Complaint {
  id: string
  ref: string
  category: IncidentCategory
  title: string
  description: string
  address: string
  localityId: string
  location: LatLng
  status: ComplaintStatus
  priority: Priority
  createdAt: string
  updatedAt: string
  assignedDepartment: string
  citizenName: string
  citizenPhone?: string
  imageUrl?: string
  imageProvenance?: 'citizen_upload' | 'demo_reference'
  aiSummary?: string
  linkedCellId?: string
  riskAtReport?: number
  timeline: ComplaintTimelineEntry[]
  resolutionNote?: string
}

export interface Incident {
  id: string
  category: IncidentCategory
  lng: number
  lat: number
  localityId: string
  occurredAt: string
  severity: 'minor' | 'moderate' | 'major'
  status: 'resolved' | 'open'
  source: 'simulated'
}

export interface HourlyWeather {
  time: string
  rainfallMm: number
  probability: number
  temperatureC: number
  humidity: number
}

export interface DailyWeather {
  date: string
  rainfallMm: number
  maxTempC: number
  minTempC: number
  probability: number
}

export interface WeatherSnapshot {
  current: {
    temperatureC: number
    humidity: number
    windKph: number
    condition: string
    rainfallLast24hMm: number
    observedAt: string
  }
  hourly: HourlyWeather[]
  daily: DailyWeather[]
  scenario: {
    label: string
    provenance: DataProvenance
    note: string
  }
}

export type ActionStatus = 'proposed' | 'approved' | 'scheduled' | 'completed'

export interface PreventiveAction {
  id: string
  ref: string
  cellId: string
  localityId: string
  title: string
  description: string
  department: string
  priority: Priority
  status: ActionStatus
  category: RiskCategory
  riskReductionPct: number
  populationBenefit: number
  estimatedCostInr: number
  dueDate: string
  rationale: string
  evidence: string[]
  createdAt: string
  origin: 'rule_engine' | 'manual'
}

export type AssetType =
  | 'stormwater_drain'
  | 'pumping_station'
  | 'road_segment'
  | 'culvert'
  | 'retention_pond'

export type AssetCondition = 'good' | 'fair' | 'poor' | 'critical'

export interface InfrastructureAsset {
  id: string
  name: string
  type: AssetType
  localityId: string
  location: LatLng
  condition: AssetCondition
  lastInspected: string
  criticality: 'low' | 'medium' | 'high'
  capacityNote: string
  notes: string
  source: 'simulated' | 'public_dataset'
}

export interface ModelInfo {
  name: string
  version: string
  algorithm: string
  status: string
  horizonHours: number
  trainedAt: string | null
  metrics: {
    precision: number | null
    recall: number | null
    f1: number | null
    prAuc: number | null
  }
  dataSources: Array<{ label: string; provenance: DataProvenance; note: string }>
  disclaimer: string
}

export interface RiskScenario {
  rainfallMmPerHour: number
  rainfallDurationHours: number
  drainageCondition: 'poor' | 'fair' | 'good'
  imperviousPct: number
}
